"""Discover marker questions reachable after independent status normalization."""
from copy import deepcopy
import hashlib
import escrow_marker_review as markers

PROFILE = 'escrow-status-equivalence-review/v6'

FRONTIER = r'''
    if globals().get('_GENERAL_E2E_RULE_REVIEW',{}).get('mode')=='discover':
        _identity_fields={'币种','合同号','客户号','账户','渠道','资金用途','分期号','收款号','应收编号','退款申请号','批次号','类型','业务编号','对象类型'}
        _marker_frontier={}
        for _reference_row in expected.get('待补与差异',[]):
            _identity=(normalized(_reference_row.get('对象类型')),normalized(_reference_row.get('业务编号')))
            if not all(_identity):continue
            for _field,_want in _reference_row.items():
                if (not _field.startswith('_') and _field not in TEXT_EXCLUDE
                        and (_field in STATE_FIELDS or _field not in _identity_fields)
                        and normalized(_want) in ('待确认','不适用')):
                    _marker_frontier.setdefault(_identity,set()).add((_field,normalized(_want)))
        for _row in actual.get('待补与差异',[]):
            _identity=(normalized(_row.get('对象类型')),normalized(_row.get('业务编号')))
            for _field,_want in sorted(_marker_frontier.get(_identity,set())):
                _value=_row.get(_field)
                if normalized(_value) not in ('','待确认','不适用') and number(_value) is None:
                    _ge2e_escrow_marker('待补与差异',_field,_row,_want)
'''


def effective_source(manifest, original, current, prior):
    if manifest.get('runtime', {}).get('rule_review_profile') != PROFILE:
        return current, prior
    projection = deepcopy(manifest)
    projection['runtime']['rule_review_profile'] = markers.PROFILE
    effective, receipt = markers.effective_source(projection, original, current, prior)
    # Match the immutable snapshot boundary generated by v4 rather than the
    # original v3 index, preserving every existing frozen v1-v5 reconstruction.
    end = '            _GE2E_ESCROW_ROWS[id(_row)]=(_table,originals,_escrow_snapshot(_row))\n'
    if effective.count(end) != 1:
        raise ValueError('ESCROW_FRONTIER_REVIEW_SOURCE_SPAN_MISMATCH')
    effective = effective.replace(end, end + FRONTIER, 1).replace(markers.PROFILE, PROFILE)
    receipt['correction_id'] = PROFILE
    receipt['effective_source_sha256'] = hashlib.sha256(effective.encode()).hexdigest()
    receipt['discovery_frontier'] = 'same original object type/business ID; possible post-status marker comparisons'
    receipt['reason'] += ' 发现阶段按同一对象类型/业务编号收齐状态规范化后可达的原标记义务，不预先判定状态或参考业务事实；原始行快照和10000上限保持。'
    return effective, receipt
