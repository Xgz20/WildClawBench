"""Read-only installed-plugin witness for an AStudio Prompt reference."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tomllib

if __package__:
    from .preprocess_windows_guest import (
        PLUGIN_MANIFESTS, REMOTE_PLUGIN_METADATA, StepError, _reparse, astudio_paths, runtime, user_path,
    )
else:
    # -I excludes ambient/user paths. Add only our uploaded helper directory for
    # this import; candidate workspace files never supply these modules.
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    try:
        from preprocess_windows_guest import (
            PLUGIN_MANIFESTS, REMOTE_PLUGIN_METADATA, StepError, _reparse, astudio_paths, runtime, user_path,
        )
    finally:
        sys.path.pop(0)

NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,119}\Z")


def manifest(root, name):
    for relative in PLUGIN_MANIFESTS:
        path = root / relative
        if path.is_file() and not _reparse(path) and path.stat().st_size <= 256 * 1024:
            value = json.loads(path.read_text(encoding="utf-8-sig"))
            if isinstance(value, dict) and value.get("name") == name:
                version = value.get("version")
                return {"version": version if isinstance(version, str) and re.fullmatch(r"[vV]?[0-9][0-9A-Za-z.+_-]{0,119}", version) else None}
    raise StepError("PROMPT_PLUGIN_MANIFEST_INVALID")


def inventory_sha(root):
    rows, total = {}, 0
    for path in sorted(root.rglob("*")):
        if _reparse(path) or not (path.is_dir() or path.is_file()):
            raise StepError("PROMPT_PLUGIN_SOURCE_UNSAFE")
        if path.is_file():
            if '__pycache__' in path.relative_to(root).parts and path.suffix == '.pyc':
                continue  # Python's generated bytecode is not a plugin source change.
            total += path.stat().st_size
            if len(rows) >= 20000 or total > 256 * 1024 * 1024:
                raise StepError("PROMPT_PLUGIN_SOURCE_TOO_LARGE")
            rows[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return hashlib.sha256(json.dumps(rows, sort_keys=True).encode()).hexdigest()


def inspect_plugins(binary, home, work, names, *, cwd=None):
    if not isinstance(names, list) or not 1 <= len(names) <= 12 or any(not isinstance(n, str) or not NAME.fullmatch(n) for n in names):
        raise StepError("PROMPT_PLUGIN_REQUEST_INVALID")
    configuration = home / "config.toml"
    plugins = {}
    if configuration.is_file():
        if _reparse(configuration) or configuration.stat().st_size > 4 * 1024 * 1024:
            raise StepError("PROMPT_PLUGIN_SOURCE_UNSAFE")
        with configuration.open("rb") as stream:
            plugins = tomllib.load(stream).get("plugins", {})
        if not isinstance(plugins, dict):
            raise StepError("PROMPT_PLUGIN_CONFIGURATION_INVALID")
    listing, skills = {}, []
    try:
        with runtime(binary, home, work, 25) as rpc:
            listing = rpc.call("plugin/installed", {"cwds": [str(cwd or work)]})
            data = rpc.call("skills/list", {"cwds": [str(cwd or work)], "forceReload": True})
            skills = [Path(skill["path"]).resolve() for group in data.get("data", [])
                      for skill in group.get("skills", [])
                      if skill.get("enabled") is True and isinstance(skill.get("path"), str)]
    except (StepError, OSError, ValueError, TimeoutError, subprocess.SubprocessError):
        # An independent app-server may not inherit the desktop catalog session.
        # The fallback is explicitly labelled as cache/config evidence.
        listing = {}
    if not isinstance(listing, dict):
        raise StepError("PROMPT_PLUGIN_INSPECTION_FAILED")
    results = []
    for name in names:
        records = [(market, plugin) for market in listing.get("marketplaces", [])
                   for plugin in market.get("plugins", [])
                   if plugin.get("id") == name + "@" + str(market.get("name"))]
        active = [(m, p) for m, p in records if p.get("installed") is True and p.get("enabled") is True
                  and p.get("availability", "AVAILABLE") == "AVAILABLE"]
        if records and not active:
            raise StepError("PROMPT_PLUGIN_DISABLED" if any(p.get("enabled") is False for _, p in records)
                            else "PROMPT_PLUGIN_NOT_AVAILABLE")
        markets = {str(m["name"]): p for m, p in active}
        cache = home / "plugins/cache"
        if not records and cache.is_dir():
            if _reparse(cache):
                raise StepError("PROMPT_PLUGIN_SOURCE_UNSAFE")
            markets = {m.name: None for m in cache.iterdir() if m.is_dir() and NAME.fullmatch(m.name)
                       and (m / name).is_dir()}
        candidates, disabled = [], False
        for market, registered in markets.items():
            if not NAME.fullmatch(market):
                raise StepError("PROMPT_PLUGIN_SOURCE_UNSAFE")
            configured = plugins.get(name + "@" + market, {})
            if not isinstance(configured, dict) or ("enabled" in configured and type(configured["enabled"]) is not bool):
                raise StepError("PROMPT_PLUGIN_CONFIGURATION_INVALID")
            if isinstance(configured, dict) and configured.get("enabled") is False:
                disabled = True
                continue
            directory = cache / market / name
            roots, identity = [], None
            if directory.is_dir():
                directory = user_path(directory)
                identity_file = directory / REMOTE_PLUGIN_METADATA
                if identity_file.is_file():
                    if _reparse(identity_file) or identity_file.stat().st_size > 32768:
                        raise StepError("PROMPT_PLUGIN_SOURCE_UNSAFE")
                    metadata = json.loads(identity_file.read_text(encoding="utf-8-sig"))
                    if not isinstance(metadata, dict):
                        raise StepError("PROMPT_PLUGIN_IDENTITY_MISMATCH")
                    identity = metadata.get("remote_plugin_id") if metadata.get("schema_version") == 1 else None
                if registered is None and (not isinstance(identity, str) or not identity.strip()):
                    continue  # A bare/stale directory is not an installation witness.
                if registered and registered.get("remotePluginId") and registered["remotePluginId"] != identity:
                    raise StepError("PROMPT_PLUGIN_IDENTITY_MISMATCH")
                roots = [user_path(p) for p in directory.iterdir() if p.is_dir() and NAME.fullmatch(p.name)]
                if len(roots) > 50:
                    raise StepError("PROMPT_PLUGIN_SOURCE_TOO_LARGE")
                observed = [root for root in roots if any(path.is_relative_to(root) for path in skills)]
                if observed:
                    roots = observed
                elif registered and isinstance(registered.get("version"), str):
                    roots = [root for root in roots if manifest(root, name)["version"] == registered["version"]]
            elif registered and (registered.get("source") or {}).get("type") == "local":
                roots = [user_path(Path(registered["source"]["path"]))]
            elif registered:
                raise StepError("PROMPT_PLUGIN_SOURCE_UNSUPPORTED")
            if len(roots) > 1:
                raise StepError("PROMPT_PLUGIN_SOURCE_AMBIGUOUS")
            for root in roots:
                info = manifest(root, name)
                candidates.append({"name": name, "marketplace": market, **info,
                    "source_path": str(root), "cache_version": root.name,
                    "tree_sha256": inventory_sha(root), "enabled": True,
                    "hash_scope": "source-tree-excluding-python-bytecode-v1",
                    "availability_evidence": "runtime-catalog" if registered else "remote-cache-and-config",
                    "runtime_observed": bool(registered),
                    "enabled_source": "runtime" if registered else "config" if isinstance(configured, dict) and configured.get("enabled") is True else "cache-default",
                    "identity_sha256": hashlib.sha256(identity.encode()).hexdigest() if isinstance(identity, str) else None})
        if not candidates:
            raise StepError("PROMPT_PLUGIN_DISABLED" if disabled else "PROMPT_PLUGIN_NOT_INSTALLED")
        if len(candidates) != 1:
            raise StepError("PROMPT_PLUGIN_SOURCE_AMBIGUOUS")
        results.append(candidates[0])
    return results


def main():
    work = Path(__file__).resolve().parent
    try:
        request = json.loads((work / "request.json").read_text(encoding="utf-8"))
        binary, _, _, home = astudio_paths()
        result = {"status": "passed", "plugins": inspect_plugins(binary, home, work, request["names"], cwd=request.get("cwd"))}
    except StepError as error:
        result = {"status": "failed", "error": str(error)}
    except (OSError, ValueError, KeyError, TypeError):
        result = {"status": "failed", "error": "PROMPT_PLUGIN_INSPECTION_FAILED"}
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
